function getNthPrimeNumber(n) {
	let primes = []
	let nums = new Array(Math.pow(2, 20)).fill(undefined).map(() => {
		const res = new Object()
		res.isPrime = true
		res.lastMultiple = 0
		return res
	})
	let i = 2

	while (i < nums.length) {
		const num = nums[i]
		if (num.isPrime) {
			let multiple = i
			while ((multiple += i) < nums.length) {
				nums[multiple].isPrime = false
			}
			num.lastMultiple = multiple - num
			primes.push(i)

			if (primes.length === n) {
				return primes[n - 1]
			}
		}
		i++
	}
	return primes
}


