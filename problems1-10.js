//returns all divisors of x
function getDivisors(x) {
	const left = new Array()
	const right = new Array()
	let i = 1
	while (i < Math.sqrt(x)) {
		if (x % i === 0) {
			left.push(i)
			right.unshift(x / i)
		}
		i++
	}

	if (i === Math.sqrt(x)) {
		left.push(i)
	}

	while (right.length > 0) {
		left.push(right.shift())
	}

	return left
}
