//returns a list of primes less than n
function primesLessThanN(n) {
	const primes = []
	const nums = new Array(Math.ceil(n)).fill(true)

	let i = 2
	while (i < n) {
		if (nums[i] === true) {
			primes.push(i)
			let sum = i
			while ((sum += i) < n) {
				nums[sum] = false
			}
		}
		i++
	}

	return primes
} 

function largestPrimeFactorOfN(n) {
	const primes = primesLessThanN(Math.sqrt(n))
	let i = primes.length - 1
	while (i >= 0 ) {
		const prime = primes[i]
		if (n % prime === 0) {
			return prime
		}
		i--
	}
}

