//Returns a list containing nums that are multiples of all the arguments provided, 
//not every multiple of every argument
function findMultiples(n, ...args) {
	const res = []

	if (args.length > 1) {
		
		//num index to num count
		let nums = new Array(n + 1).fill(0)

		//let m = num of args, if numCount === m, add to res
		for (const num of args) {
			let sum = num
			while (sum <= n) {
				nums[sum]++

				// if (nums[sum] === args.length) {
				// 	res.push(sum)
				// }
				sum += num
			}
			for (let i = 0; i < nums.length; i++) {
				if (nums[i] === args.length) res.push(i)
			}
		}
	} else {
		
		let num = args[0]
		
		while (num <= n) {
			res.push(num)
			num += args[0]
		}
	}

	return res
}

function findSumOfMultiples(n, ...args) {
	let res = 0
	for (const num of args) {
		res += findMultiples(n, num).reduce((acc, curr) => acc + curr)
	}
	res -= findMultiples(n, ...args).reduce((acc, curr) => acc + curr)
	return res

}
